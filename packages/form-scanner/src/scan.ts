let scanSequence = 0

interface FrameContext {
  frame: string
  shadow: boolean
  /** The subtree we enumerate (Document, ShadowRoot, or a scoped Element). */
  walk: Document | ShadowRoot | Element
  /** Where id-based label/aria lookups resolve (may differ from `walk` when scoped). */
  lookup: Document | ShadowRoot
}

/** DOM ids generated by frameworks (React useId, MUI, emotion) — never meaningful. */
const GENERATED_ID_RE = /^(_r_[0-9a-z]+_|:r[0-9a-z]+:|«r[0-9a-z]+»|mui-\d+|css-[0-9a-z]+)$/i

/** True when a string is purely a framework-generated token (no human meaning). */
function isGeneratedToken(value: string | undefined): boolean {
  return !!value && GENERATED_ID_RE.test(value)
}

/**
 * A field with no human-usable identity whose only "name"/id is a generated token
 * (e.g. `_r_f4_`, `:r9:`). These are noise — usually hidden inputs inside custom
 * widgets, or framework-internal controls. A generated `name` counts as junk just
 * like a generated `id`: React's `useId` feeds both, so `name="_r_42_"` is no more
 * meaningful than `id="_r_42_"`. A real `name`/label/aria/placeholder rescues it.
 */
function isJunkField(f: DetectedField): boolean {
  const meaningfulName = f.name && !isGeneratedToken(f.name) ? f.name : undefined
  const hasIdentity =
    f.labelText || meaningfulName || f.ariaLabel || f.ariaLabelledByText || f.placeholder
  if (hasIdentity) return false
  return isGeneratedToken(f.domId) || isGeneratedToken(f.name)
}

function lookupOf(root: Document | ShadowRoot | Element): Document | ShadowRoot {
  if (root.nodeType === 9 || root.nodeType === 11) return root as Document | ShadowRoot
  return (root as Element).getRootNode() as Document | ShadowRoot
}

/**
 * Scan a document or element (and its open shadow roots + same-origin iframes)
 * for fillable fields, including custom (non-native) dropdowns. Returns
 * DetectedField[] plus honest limitations. Pure DOM — no Chrome, no Vue.
 */
export function scanForms(
  root: Document | Element = document,
  options: ScanOptions = { includeHidden: false, scope: 'auto' },
): ScanResult {
  const fields: DetectedField[] = []
  const fieldEls: Element[] = []
  const limitations: ScanLimitation[] = []
  // Roots of detected custom widgets; their internal controls are suppressed.
  const suppressed: Element[] = []
  // Radios sharing a (frame, name) collapse into ONE field carrying their options,
  // so they fill by picking the right option — not as N independent booleans.
  const radioGroups = new Map<string, { field: DetectedField; members: HTMLInputElement[] }>()
  let counter = 0
  let frameCounter = 0
  const scanId = ++scanSequence
  const rootIds = new Map<Node, number>()
  const rootId = (node: Node): number => {
    if (!rootIds.has(node)) rootIds.set(node, rootIds.size)
    return rootIds.get(node)!
  }

  const isSuppressed = (el: Element): boolean => suppressed.some((root) => root.contains(el))

  /** Fold a named radio into its group field (creating it on first sight). */
  const addRadio = (input: HTMLInputElement, ctx: FrameContext): void => {
    const key = `${rootId(input.getRootNode())}:${rootId(input.form ?? input.getRootNode())}:${input.name}`
    const existing = radioGroups.get(key)
    if (existing) {
      existing.members.push(input)
      existing.field.options?.push(radioOption(input, ctx.lookup))
      return
    }
    const field = buildRadioGroupField(input, ctx, `qf-${scanId}-${counter}`)
    const visibleEnough = options.includeHidden || field.visible
    const fillable = options.includeNonFillable || !field.disabled
    if (!visibleEnough || !fillable) return
    input.setAttribute('data-qf-id', field.id)
    fields.push(field)
    fieldEls.push(input)
    counter++
    radioGroups.set(key, { field, members: [input] })
  }

  const push = (field: DetectedField, el: Element): void => {
    const visibleEnough = options.includeHidden || field.visible
    // A readonly input is normally non-fillable — EXCEPT a calendar widget's input,
    // which is readonly only because you pick from its popup. Keep those so the probe
    // can confirm them and the datepicker fill path (calendar-click) can drive them.
    const fillable =
      options.includeNonFillable ||
      (!field.disabled && (!field.readonly || looksLikeDatepickerInput(el)))
    if (visibleEnough && fillable && !isJunkField(field)) {
      // Stamp a stable per-element marker. Fill resolves by `[data-qf-id="..."]`
      // first, guaranteeing it writes to the exact element detected here — never a
      // different element that merely shares a fuzzy selector (name/structural path).
      el.setAttribute('data-qf-id', field.id)
      fields.push(field)
      fieldEls.push(el)
      counter++
    }
  }

  /** Drop already-collected fields that live inside a newly-found widget root. */
  const dropInside = (widgetRoot: Element): void => {
    for (let i = fieldEls.length - 1; i >= 0; i--) {
      if (widgetRoot.contains(fieldEls[i])) {
        fieldEls[i].removeAttribute('data-qf-id')
        fields.splice(i, 1)
        fieldEls.splice(i, 1)
      }
    }
  }

  const visit = (ctx: FrameContext): void => {
    const elements = ctx.walk.querySelectorAll('*')
    for (const el of Array.from(elements)) {
      if (el.closest('[data-quikfill-ui]')) continue
      if (isSuppressed(el)) continue
      // Framework form-payload proxies are not independent user controls.
      if (
        el.matches(
          'input[data-hidden], select[aria-hidden="true"], input[aria-hidden="true"][tabindex="-1"]',
        )
      )
        continue

      if (el.getAttribute('role') === 'radiogroup') {
        const radios = Array.from(el.querySelectorAll('[role="radio"]')).filter(
          (r) => r.closest('[role="radiogroup"]') === el,
        )
        if (radios.length) {
          const field = buildField(el as FormControl, ctx, `qf-${scanId}-${counter}`)
          field.inputType = 'radiogroup'
          field.options = radios.map((r) => ({
            value: toggleValue(r),
            label: getLabelText(r as FormControl, ctx.lookup) ?? toggleValue(r),
            selected: r.getAttribute('aria-checked') === 'true',
            disabled: r.getAttribute('aria-disabled') === 'true' || r.matches(':disabled'),
          }))
          field.currentValue = field.options.find((o) => o.selected)?.value ?? null
          push(field, el)
          suppressed.push(el)
          continue
        }
      }
      if (isAriaToggle(el) && el.getAttribute('role') !== 'radio') {
        const field = buildField(el as FormControl, ctx, `qf-${scanId}-${counter}`)
        field.inputType = el.getAttribute('role') === 'switch' ? 'switch' : 'checkbox'
        const state = el.getAttribute('aria-checked')
        field.currentValue = state === 'false' ? null : (state ?? null)
        field.required ||= el.getAttribute('aria-required') === 'true'
        field.disabled ||= el.getAttribute('aria-disabled') === 'true'
        field.readonly ||=
          el.getAttribute('aria-readonly') === 'true' ||
          !['true', 'false', 'mixed'].includes(state ?? '')
        push(field, el)
        suppressed.push(el)
        continue
      }

      if (isCustomSelectTrigger(el)) {
        const info = detectCustomSelect(el)
        if (info) {
          dropInside(info.widgetRoot)
          push(buildCustomField(info, ctx, `qf-${scanId}-${counter}`), info.widgetRoot)
          suppressed.push(info.widgetRoot)
          continue
        }
      }
      if (isFormControl(el)) {
        const input = el as HTMLInputElement
        if (el.tagName.toLowerCase() === 'input' && input.type === 'radio' && input.name) {
          addRadio(input, ctx)
          continue
        }
        push(buildField(el, ctx, `qf-${scanId}-${counter}`), el)
      }

      // Descend into an open shadow root if present.
      const shadow = (el as Element & { shadowRoot?: ShadowRoot | null }).shadowRoot
      if (shadow) {
        visit({ frame: ctx.frame, shadow: true, walk: shadow, lookup: shadow })
      }
    }

    // Same-origin iframes only; cross-origin access throws → reported.
    for (const frame of Array.from(ctx.walk.querySelectorAll('iframe'))) {
      const iframe = frame as HTMLIFrameElement
      try {
        const innerDoc = iframe.contentDocument
        if (innerDoc) {
          visit({
            frame: `frame:${frameCounter++}`,
            shadow: ctx.shadow,
            walk: innerDoc,
            lookup: innerDoc,
          })
        } else {
          limitations.push({
            kind: 'crossOriginFrame',
            detail: `Cannot read iframe ${iframe.src || '(no src)'} — likely cross-origin.`,
          })
        }
      } catch {
        limitations.push({
          kind: 'crossOriginFrame',
          detail: `Cross-origin iframe ${iframe.src || '(no src)'} is not accessible.`,
        })
      }
    }
  }

  // Clear markers from a prior scan: an element no longer detected would otherwise
  // keep a stale data-qf-id that could shadow the current scan's marker at fill time.
  const clearMarkers = (scope: Document | Element | ShadowRoot): void => {
    for (const el of Array.from(scope.querySelectorAll('*'))) {
      el.removeAttribute('data-qf-id')
      if (el.shadowRoot) clearMarkers(el.shadowRoot)
      if (el.tagName.toLowerCase() === 'iframe') {
        try {
          const inner = (el as HTMLIFrameElement).contentDocument
          if (inner) clearMarkers(inner)
        } catch {
          /* cross-origin */
        }
      }
    }
  }
  clearMarkers(root)

  visit({ frame: 'main', shadow: false, walk: root, lookup: lookupOf(root) })

  // Finalize each radio group now that all its members (and options) are known:
  // selection, visibility, required, and a fingerprint over the full option set.
  for (const { field, members } of radioGroups.values()) {
    const checked = members.find((m) => m.checked)
    field.currentValue = checked ? checked.value : null
    field.visible = members.some((m) => isVisible(m))
    field.required = members.some((m) => m.required || m.hasAttribute('required'))
    field.domFingerprint = fingerprint({
      label: field.labelText,
      name: field.name,
      type: 'radiogroup',
      options: field.options?.map((o) => o.label),
      section: field.sectionHeading,
    }).hash
  }

  return {
    fields,
    limitations,
    structureHash: structureHash(fields),
  }
}

/** One option from a single radio: its value + visible label + selected state. */
function radioOption(input: HTMLInputElement, lookup: Document | ShadowRoot): FieldOption {
  return {
    value: input.value,
    label: getLabelText(input, lookup) ?? input.value,
    selected: input.checked,
    disabled: input.matches(':disabled'),
  }
}

/**
 * Build the group field from its first radio. Options/selection/fingerprint are
 * finalized after the walk (more members may follow). `selectorCandidates` is the
 * name selector that matches every member, so the filler can pick the right one.
 */
function buildRadioGroupField(
  radio: HTMLInputElement,
  ctx: FrameContext,
  id: string,
): DetectedField {
  const name = radio.name
  const labelText = getRadioGroupLabel(radio)
  const sectionHeading = getSectionHeading(radio)
  return {
    id,
    tagName: 'input',
    inputType: 'radiogroup',
    currentValue: radio.checked ? radio.value : null,
    required: radio.required || radio.hasAttribute('required'),
    disabled: radio.matches(':disabled'),
    readonly: false,
    visible: isVisible(radio),
    name,
    classNames: (radio.getAttribute('class') ?? '').split(/\s+/).filter(Boolean),
    ariaLabel: getAriaLabel(radio),
    labelText,
    sectionHeading,
    options: [radioOption(radio, ctx.lookup)],
    selectorCandidates: [`input[type="radio"][name="${cssEscape(name)}"]`],
    domFingerprint: '',
    frame: ctx.frame,
    shadow: ctx.shadow,
  }
}

function buildField(el: FormControl, ctx: FrameContext, id: string): DetectedField {
  const inputType = getInputType(el)
  const labelText = getLabelText(el, ctx.lookup)
  const name = el.getAttribute('name') ?? undefined
  const options = getOptions(el)
  const sectionHeading = getSectionHeading(el)
  const fp = fingerprint({
    label: labelText,
    name,
    type: inputType,
    options: options?.map((o) => o.label),
    section: sectionHeading,
  })
  const asInput = el as HTMLInputElement

  return {
    id,
    tagName: el.tagName.toLowerCase(),
    inputType,
    currentValue: getCurrentValue(el),
    required: el.hasAttribute('required') || asInput.required === true,
    disabled: el.matches(':disabled') || el.hasAttribute('disabled') || asInput.disabled === true,
    readonly: el.hasAttribute('readonly') || asInput.readOnly === true,
    visible: isVisible(el),
    name,
    domId: el.getAttribute('id') ?? undefined,
    classNames: (el.getAttribute('class') ?? '').split(/\s+/).filter(Boolean),
    placeholder: el.getAttribute('placeholder') ?? undefined,
    autocomplete: el.getAttribute('autocomplete') ?? undefined,
    ariaLabel: getAriaLabel(el),
    ariaLabelledByText: getAriaLabelledByText(el, ctx.lookup),
    labelText,
    nearbyText: getNearbyText(el),
    sectionHeading,
    options,
    autocompleteHint: detectAutocomplete(el),
    mask: getMaskPattern(el),
    ...getValidationAttrs(el),
    selectorCandidates: getSelectorCandidates(el),
    domFingerprint: fp.hash,
    frame: ctx.frame,
    shadow: ctx.shadow,
  }
}

/** Build a single DetectedField for a custom (non-native) select widget. */
function buildCustomField(info: CustomSelectInfo, ctx: FrameContext, id: string): DetectedField {
  const { widgetRoot, trigger } = info
  const labelText = getWidgetLabel(widgetRoot, ctx.lookup)
  const name = widgetRoot.getAttribute('name') ?? trigger.getAttribute('name') ?? undefined
  const sectionHeading = getSectionHeading(widgetRoot)
  const options = info.optionLabels.map((label) => ({
    value: label,
    label,
    selected: label === info.selectedLabel,
    ...(info.disabledOptionLabels.includes(label) ? { disabled: true } : {}),
  }))
  const fp = fingerprint({
    label: labelText,
    name,
    type: 'customSelect',
    options: info.optionLabels,
    section: sectionHeading,
  })

  const customWidget: CustomWidget = {
    kind: info.kind,
    triggerSelectorCandidates: getTriggerSelectorCandidates(trigger),
    valueDisplaySelectorCandidates: info.valueDisplay
      ? getSelectorCandidates(info.valueDisplay)
      : [],
    optionItemSelector: info.optionItemSelector,
    optionsOpenOnDemand: true,
    listboxId: info.listboxId ?? undefined,
    searchInputSelector: info.searchInput ? getSelectorCandidates(info.searchInput)[0] : undefined,
    optionValueAttr: info.optionValueAttr ?? undefined,
    isSearchable: info.isSearchable,
    isVirtualized: info.isVirtualized,
    selectionItemSelector: info.selectionItemSelector,
  }

  return {
    id,
    tagName: widgetRoot.tagName.toLowerCase(),
    inputType: 'customSelect',
    currentValue: info.selectedLabel,
    required: widgetRoot.getAttribute('aria-required') === 'true',
    disabled: trigger.getAttribute('aria-disabled') === 'true',
    readonly: false,
    visible: isVisible(widgetRoot),
    name,
    domId: widgetRoot.getAttribute('id') ?? undefined,
    classNames: (widgetRoot.getAttribute('class') ?? '').split(/\s+/).filter(Boolean),
    ariaLabel: getAriaLabel(trigger) ?? getAriaLabel(widgetRoot),
    ariaLabelledByText: getAriaLabelledByText(trigger, ctx.lookup),
    labelText,
    sectionHeading,
    options,
    customWidget,
    selectorCandidates: getSelectorCandidates(widgetRoot),
    domFingerprint: fp.hash,
    frame: ctx.frame,
    shadow: ctx.shadow,
  }
}
